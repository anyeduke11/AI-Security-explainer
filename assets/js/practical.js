  /* 本地判分：纯规则比对，不 eval、不执行任何用户输入
   * answer: { picked: [optionId...], hint: bool } */
  function score(task, answer) {
    var picked = (answer && answer.picked) || [];
    var key = task.key || [];
    var hit = key.filter(function (k) { return picked.indexOf(k) >= 0; });
    var miss = key.filter(function (k) { return picked.indexOf(k) < 0; });
    var bad = (task.forbidden || []).filter(function (k) { return picked.indexOf(k) >= 0; });
    var extra = picked.filter(function (p) { return key.indexOf(p) < 0 && (task.forbidden || []).indexOf(p) < 0; });
    var stepsRate = key.length ? hit.length / key.length : 0;
    /* 顺序必须按用户实际选择顺序计算，不能用 key.filter()（那会永远按标准顺序） */
    var seq = picked.filter(function (p) { return key.indexOf(p) >= 0; });
    var orderRate = seq.length ? 1 : 0;
    if (task.type === 'steps' && seq.length > 1) {
      var ok = 0;
      for (var i = 1; i < seq.length; i++) if (key.indexOf(seq[i]) > key.indexOf(seq[i - 1])) ok++;
      orderRate = ok / (seq.length - 1);
    }
    var targetHit = !miss.length && !bad.length ? 1 : 0;
    var w = task.scoring.weights;
    var raw = 100 * (stepsRate * w.steps + orderRate * w.order + targetHit * w.target);
    var value = Math.max(0, Math.round(raw - bad.length * 15 - (answer && answer.hint ? 10 : 0)));
    return {
      score: value,
      pass: value >= task.scoring.pass,
      master: value >= task.scoring.master,
      hit: hit, miss: miss, bad: bad, extra: extra,
      rates: { steps: Math.round(stepsRate * 100), order: Math.round(orderRate * 100), target: targetHit ? 100 : 0 }
    };
  }

